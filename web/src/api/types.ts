/** Contract types, hand-written from docs/data-contract.md.
 * The fire-history, risk-shard and live-detection contracts left with
 * the fire/live views (task 49); the field-engine contracts follow. */

export interface Card {
  id: string;
  value: number | string | null;
  unit?: string | null;
  text: string;
  /** English rendering of `text` (the Spanish one feeds the engines). */
  text_en?: string;
  source: string;
  resolution?: string;
  confidence: "high" | "medium" | "low";
  /** rain card: 12 monthly means mm/month (2001 -> last full year). */
  rain_monthly_mm?: number[];
  /** Scenario present: unmodified baseline value + numeric delta. */
  baseline_value?: number | string | null;
  delta?: number;
  generated_at?: string;
  valid_until?: string;
  /** fire_weather card: single INTA stop conditions met (last 3 days). */
  stop_conditions?: string[];
  stop_detail?: Record<string, string>;
  stop_detail_en?: Record<string, string>;
}

export interface CalendarRow {
  id: string;
  label?: string;
  levels: (number | null)[];
}

export interface Measure {
  id: string;
  name: string;
  name_en?: string;
  why_en?: string;
  factor?: string;
  why?: string;
  benefit?: string;
  requires?: Record<string, unknown>;
  /** Extra checklist items (e.g. harvester checks from the INTA Chaco
   * guide). */
  checks?: string[];
  cost?: string;
  source?: string;
}

export interface DiagnoseResponse {
  diagnosis_id: string;
  area_ha: number;
  centroid: [number, number];
  /** Compatible additions 2026-11: agronomic zone/province/country of
   * the plot centroid (`zone` is read by /api/field/rotations). */
  zone?: string;
  province?: string | null;
  country?: string | null;
  h3_r5: string[];
  h3_r6: string[];
  cards: Card[];
  coverage?: { available_cards: number; total_cards: number; comparable: boolean };
  terrain_coverage?: number | null;
  land_cover?: string | null;
  calendar: { months: string[]; rows: CalendarRow[] };
  baseline?: Pick<DiagnoseResponse, "cards" | "calendar">;
  measures?: Measure[];
  measures_gaps?: string[];
  /** Climate scenario applied to the daily series (echoed). */
  scenario?: { rain_pct: number; temp_delta_c: number };
  /** Elevation correction (task 20): plot vs POWER cell altitude and
   * the adjustment applied to T2M_MAX/T2M_MIN (−6.5 °C/km). */
  elevation_m?: number | null;
  power_cell_elevation_m?: number | null;
  temp_adjust_c?: number;
  /** Degraded response: the backend returned whatever it could without
   * some sources. The UI shows the reason + retry, never a blank. */
  degraded?: boolean;
  degraded_reason?: string;
  /** How well the satellite sees this plot (task 44): typical errors
   * from our own validations. */
  accuracy?: DiagAccuracy;
  /** Last 24 months + current partial vs 2001-2020 normals (task 47). */
  timeline?: DiagTimeline;
}

/** One timeline variable; `normal` holds 12 monthly normals applied
 * by calendar month, anomalies are per month. */
export interface TimelineSeriesData {
  values: (number | null)[];
  normal?: (number | null)[];
  anomaly_pct?: (number | null)[];
  anomaly_c?: (number | null)[];
}

export interface DiagTimeline {
  /** "YYYY-MM" — last 24 complete months plus the current one. */
  months: string[];
  partial_last?: boolean;
  /** Plain-language season summary generated by the back end. */
  headline?: string;
  series: {
    rain_mm?: TimelineSeriesData;
    tmax_c?: TimelineSeriesData;
    root_moisture?: TimelineSeriesData;
    heat_days_35?: TimelineSeriesData;
    frost_days?: TimelineSeriesData;
  };
  normals_period?: string;
  basis?: string;
  source?: string;
}

export interface DiagAccuracy {
  temp_rmse_c?: number | null;
  temp_rmse_adjusted_c?: number | null;
  rain_bias_mm_month?: number | null;
  rain_rmse_mm_month?: number | null;
  rain_r?: number | null;
  stations?: { temperature?: number | null; rain?: number | null };
  /** Temperature lapse-rate correction applied (°C), echoed here. */
  elevation_correction_c?: number | null;
  note?: string;
  sources?: string[];
}

export type MoistureKind = "dry" | "middle" | "wet" | "missing";
type Coordinate = [number, number];
export interface MoistureZone {
  kind: MoistureKind;
  ha: number;
  geometry: { type: "Polygon"; coordinates: Coordinate[][] } |
            { type: "MultiPolygon"; coordinates: Coordinate[][][] };
}
export type MoistureResult = { status: "no_detail" | "unavailable" } | {
  status: "available"; coverage: number; date: string; resolution_m: number;
  zones: MoistureZone[];
};

export interface Strategy {
  id: string;
  name: string;
  name_en?: string;
  is_current: boolean;
  score: number;
  confidence: string;
  indicators: Record<string, unknown>;
  why: string;
  evidence: { text: string; indicator: string; source?: string }[];
  benefits: Record<string, unknown>;
  gaps: string[];
  risks: string[];
  sequence: { crop: string; start: string; end: string; cover?: boolean }[];
  measures?: Measure[];
  measures_gaps?: string[];
}

export interface RotationsResponse {
  diagnosis_id?: string;
  strategies: Strategy[];
  disclaimer: string;
  /** "low" when the zone has no validated rotation (e.g. Patagonia). */
  confidence?: string;
  /** Top-level gaps, e.g. "sin rotaciones validadas para esta zona". */
  gaps?: string[];
  /** Documented rotation references for zones without a computed one
   * (e.g. INTA Patagonia); shown in the empty state, never computed. */
  zone_references?: { zone: string; text: string; source: string }[];
  /** Strategy ids ranked without scenario (diagnosis carried one). */
  baseline_order?: string[];
}

export interface ExplainResponse {
  strategies: { id: string; text: string; cites?: string[] }[];
  /** "ai" = validated model paragraph; "template" = fallback. */
  mode?: "ai" | "template";
}

export interface RotationEntry {
  id: string;
  name: { es?: string; en?: string };
  years: number;
  sequence: { crop: string; start: string; end: string }[];
}

export interface CropEntry {
  id: string;
  name: { es?: string; en?: string };
}

export interface CropRecommendations {
  status: "ok" | "missing_climate" | "missing_harvest" | "perennial" | "no_catalog";
  available_from: string | null;
  options: {
    id: string; name: CropEntry["name"]; score: number; conditional: boolean;
    conditions?: ("water" | "frost" | "rain_missing")[];
    sow_from: string; sow_until: string;
    water_demand_mm: number; rain_mm: number | null; rain_period?: "cycle" | "year";
    needs_irrigation: boolean;
    fits_frost: boolean | null; different_family: boolean; same_family: boolean;
  }[];
}

/** A documented incident shown next to the prevention measures
 * (`knowledge/cases.json`, contract 3.4). kind news_report = a press
 * report, not a worker testimony. */
export interface CaseEntry {
  id: string;
  place: string;
  date: string;
  summary: string;
  unknown?: string;
  source: { title?: string; url?: string };
  lessons?: string[];
  kind?: string;
}

/* ------------------------------------------------- orin (contract 2.9) -- */

export interface OrinVariable {
  id: string;                       // temp_max | temp_min | ndvi | soil_moisture
  satellite: { dataset: string; resolution: string; period: string };
  field: { source: string; n_sites: number };
  n: number;
  rmse: number;
  bias: number;                     // satellite minus field
  r: number;
  rmse_adjusted?: number;           // after elevation correction (task 20)
  bias_adjusted?: number;
  r_adjusted?: number;
  adjustment?: string;
  /** "field" = weather stations; "finer_satellite" = a finer satellite
   * used as reference (e.g. Sentinel-2 vs MODIS). Absent on old files. */
  reference_kind?: "field" | "finer_satellite";
  unit: string;
  quality: "good" | "fair" | "poor";
}

export interface OrinValidation {
  version: string;
  synthetic?: boolean;
  generated_at?: string;
  source?: string;
  variables: OrinVariable[];
}

export interface OrinLotProps {
  id: string;
  name: string;
  crop_label: string;
  zone: string;
  synthetic?: boolean;
  real_data_available?: boolean;
}

export interface OrinLots {
  type: "FeatureCollection";
  synthetic?: boolean;
  features: {
    type: "Feature";
    geometry: { type: "Polygon"; coordinates: number[][][] };
    properties: OrinLotProps;
  }[];
}

/** POST /api/field/crop — crop detected per campaign (INTA MNC). */
export type CropSeason = {
  season: "summer" | "winter";
  campaign: string;
  status: "crop" | "fallow" | "non_agricultural" | "no_coverage" | "unavailable";
  crop: { id: string; es: string; en: string } | null;
  /** share of the classified pixels that voted for this class */
  share: number | null;
  /** share of the parcel with a known class */
  coverage: number | null;
};
export type CropDetection = {
  source: string; source_url: string; resolution_m: number;
  seasons: CropSeason[];
};

/** POST /api/field/crop-zones — the field split into one zone per crop. */
export type CropZones = {
  status: "available" | "no_coverage" | "unavailable" | "no_detail";
  season: "summer" | "winter"; campaign: string;
  source: string; source_url: string; resolution_m: number;
  zones: { crop: { id: string; es: string; en: string }; ha: number;
           geometry: { type: "Polygon" | "MultiPolygon"; coordinates: unknown } }[];
};

/** POST /api/field/current-crop — what is on the field now (Sentinel-2). */
export type CurrentCropZone = {
  class: { id: string; es: string; en: string; short_es: string; short_en: string };
  kind: "crop" | "fallow" | "perennial"; ha: number; share: number;
  geometry: { type: "Polygon" | "MultiPolygon"; coordinates: unknown };
};
export type CurrentCrop = {
  status: "available" | "no_detail" | "no_coverage" | "unavailable";
  source: string; resolution_m: number; season: string;
  as_of: string | null; zones: CurrentCropZone[];
};
